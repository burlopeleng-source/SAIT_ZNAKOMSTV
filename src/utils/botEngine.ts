function getRandomItem<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateBotResponse(message: string, profile: Profile): string {
  const lowerMessage = message.toLowerCase();

  // Check personality-specific responses first
  const personalityResponsesList = personalityResponses[profile.personality] || [];
  for (const responseGroup of personalityResponsesList) {
    if (responseGroup.keywords.some(keyword => lowerMessage.includes(keyword))) {
      return getRandomItem(responseGroup.responses);
    }
  }

  // Check common responses
  for (const responseGroup of commonResponses) {
    if (responseGroup.keywords.some(keyword => lowerMessage.includes(keyword))) {
      return getRandomItem(responseGroup.responses);
    }
  }

  // Default response based on personality
  return getRandomItem(defaultResponses[profile.personality]);
}

export function getTypingDelay(message: string): number {
  // Simulate typing speed: 50-100ms per character, minimum 1 second
  const baseDelay = Math.max(1000, message.length * 60);
  // Add some randomness
  return baseDelay + Math.random() * 1000;
}
